// The quest editor's bridge between the Reedwater Delta Atlas page and the game.
// The editor is the Quests mode of the atlas's Edit world screen. It keeps one document per side quest in the atlas
// database (collection `quests`; `quests/_shared` holds the lastEditAt/shippedAt marker). This script turns a download
// of that collection into src/quest-data.js, so shipping quest edits is a one-file PR.
//
//   node scripts/quest-editor.mjs export <db-dir>   writes src/quest-data.js from <db-dir>/quests/*.json
//   node scripts/quest-editor.mjs seed <out-dir>    writes the game's current quests as editor documents
//   node scripts/quest-editor.mjs meta <file>       writes the editor's lists of creatures and items (world/quest-editor.json)
//
// Quest givers are villagers from src/world-data.js. A quest for a villager placed in the editor but not shipped yet
// also needs <db-dir>/npcs/ (the world editor's download), and the world editor changes shipped alongside.
import {readdir,readFile,writeFile,mkdir} from 'node:fs/promises';
import {join} from 'node:path';

export const MAX_LEVEL=150;
const num=(v,min,max,fallback)=>typeof v==='number'&&Number.isFinite(v)?Math.min(max,Math.max(min,v)):fallback;
const text=(v,max)=>typeof v==='string'?v.trim().slice(0,max):'';
const id=v=>typeof v==='string'&&/^[a-z0-9][a-z0-9-]{0,63}$/.test(v)?v:null;

// Editor documents to the game's quest list. Anything the game cannot use is dropped with a note rather than shipped.
// givers: villager id → name. species: creatures that can be hunted. items: item names the game knows.
export function fromEditor(docs,{givers,species,items},notes=[]){
 const rows=docs.filter(d=>d.id!=='_shared').sort((a,b)=>((a.order??1e6)-(b.order??1e6))||String(a.id).localeCompare(b.id));
 const out=[];
 for(const d of rows){
  const name=text(d.title,60)||d.id;
  if(!id(d.id)){notes.push(`Skipped quest “${name}”: its id is not usable.`);continue;}
  if(d.enabled===false){notes.push(`Held back ${d.id}: it is switched off in the editor.`);continue;}
  if(!givers.has(d.giver)){notes.push(`Skipped ${d.id}: its giver ${d.giver||'(none)'} is not a villager in the game.`);continue;}
  const objectives=[];
  for(const o of Array.isArray(d.objectives)?d.objectives:[]){
   const count=Math.round(num(o?.count,1,99,1));
   if(o?.type==='kill'&&species.has(o.species))objectives.push({type:'kill',species:o.species,count});
   else if(o?.type==='collect'&&items.has(o.item))objectives.push({type:'collect',item:o.item,count});
   else notes.push(`Dropped an objective from ${d.id}: ${o?.species||o?.item||'nothing'} is not in the game.`);
  }
  if(!objectives.length){notes.push(`Skipped ${d.id}: it has nothing to do.`);continue;}
  const r=d.rewards||{},rewardItems=[];
  for(const i of Array.isArray(r.items)?r.items:[]){
   if(items.has(i?.name))rewardItems.push({name:i.name,count:Math.round(num(i.count,1,99,1))});
   else notes.push(`Dropped reward ${i?.name||'(blank)'} from ${d.id}: no such item.`);
  }
  const quest={id:d.id,giver:d.giver,giverName:givers.get(d.giver),title:name};
  const minLevel=Math.round(num(d.minLevel,1,MAX_LEVEL,1));if(minLevel>1)quest.minLevel=minLevel;
  const requires=(Array.isArray(d.requires)?d.requires:[]).filter(id);if(requires.length)quest.requires=requires;
  Object.assign(quest,{objectives,rewards:{marks:Math.round(num(r.marks,0,10000,0)),xp:Math.round(num(r.xp,0,100000,0)),items:rewardItems},
   lore:text(d.lore,700),where:text(d.where,300),offer:text(d.offer,400),thought:text(d.thought,400),reminder:text(d.reminder,200),done:text(d.done,400)});
  out.push(quest);
 }
 // A chain only holds quests that ship: a missing or held-back quest would lock the rest forever.
 const shipped=new Set(out.map(q=>q.id));
 for(const q of out)if(q.requires){const keep=q.requires.filter(r=>shipped.has(r)&&r!==q.id);if(keep.length<q.requires.length)notes.push(`${q.id} no longer waits for ${q.requires.filter(r=>!keep.includes(r)).join(', ')}: not in the game.`);if(keep.length)q.requires=keep;else delete q.requires;}
 return out;
}

// The game's quests back to editor documents, for the first load and for resetting the editor to what is shipped.
export const toEditor=quests=>quests.map((q,i)=>{const {giverName,...rest}=q;return {...rest,minLevel:q.minLevel||1,requires:q.requires||[],enabled:true,order:i+1};});

// One quest per block and one field per line, so an edited line of dialogue is a one-line diff.
export function formatQuestData(quests){
 const j=v=>JSON.stringify(v).replace(/"([a-zA-Z_][a-zA-Z0-9_]*)":/g,'$1:');
 const block=q=>' {\n'+Object.entries(q).map(([k,v])=>`  ${k}:${j(v)}`).join(',\n')+'\n }';
 return `// Side quests: who gives them, what they ask, when they unlock, what they pay and the story behind them.
// Generated by the quest editor (Reedwater Delta Atlas → Edit world → Quests) with scripts/quest-editor.mjs. Edit them
// there and ship from there; hand edits work too, but the next export from the editor replaces this file.
export const QUEST_DATA=Object.freeze([
${quests.map(block).join(',\n')}
]);
`;
}

async function readCollection(dir,name){
 const path=join(dir,name);let files=[];try{files=(await readdir(path)).filter(f=>f.endsWith('.json'));}catch{return [];}
 const docs=[];for(const f of files){const raw=JSON.parse(await readFile(join(path,f),'utf8'));const d=raw.data&&typeof raw.data==='object'?raw.data:raw;docs.push({...d,id:d.id||f.replace(/\.json$/,'')});}
 return docs;
}

// What the game can use: its villagers (plus any downloaded with the quests), creatures and items.
export async function gameLists(extraNpcs=[]){
 const [{WORLD_DATA},{ANIMAL_TYPES},{ICONS}]=await Promise.all([import('../src/world-data.js'),import('../src/entities.js'),import('../src/item-icons.js')]);
 const givers=new Map([...WORLD_DATA.npcs,...extraNpcs].filter(n=>id(n.id)).map(n=>[n.id,text(n.name,40)||'Villager']));
 return {givers,species:new Set(Object.keys(ANIMAL_TYPES).filter(s=>!ANIMAL_TYPES[s].boss)),items:new Set(Object.keys(ICONS))};
}

if(import.meta.url===`file://${process.argv[1]}`){
 const [cmd,dir]=process.argv.slice(2);
 if(cmd==='export'&&dir){
  const notes=[],lists=await gameLists(await readCollection(dir,'npcs'));
  const quests=fromEditor(await readCollection(dir,'quests'),lists,notes);
  await writeFile('src/quest-data.js',formatQuestData(quests));
  console.log(`src/quest-data.js: ${quests.length} quests.`);
  for(const n of notes)console.log('  note:',n);
 }else if(cmd==='seed'&&dir){
  const {QUEST_DATA}=await import('../src/quest-data.js');
  await mkdir(join(dir,'quests'),{recursive:true});
  for(const d of toEditor(QUEST_DATA))await writeFile(join(dir,'quests',`${d.id}.json`),JSON.stringify(d,null,1));
  console.log(`Seed written to ${dir}/quests.`);
 }else if(cmd==='meta'&&dir){
  const [{ANIMAL_TYPES},{ICONS},{WORLD_DATA}]=await Promise.all([import('../src/entities.js'),import('../src/item-icons.js'),import('../src/world-data.js')]);
  const species=Object.entries(ANIMAL_TYPES).filter(([,a])=>!a.boss).map(([id,a])=>({id,name:a.name||id,habitat:a.habitat||'land'})).sort((a,b)=>a.name.localeCompare(b.name));
  const items=Object.entries(ICONS).map(([name,icon])=>({name,icon})).sort((a,b)=>a.name.localeCompare(b.name));
  await writeFile(dir,JSON.stringify({maxLevel:MAX_LEVEL,species,items,shippedNpcs:WORLD_DATA.npcs.map(n=>n.id)}));
  console.log(`${dir}: ${species.length} creatures, ${items.length} items.`);
 }else{console.log('Usage: node scripts/quest-editor.mjs export <db-dir> | seed <out-dir> | meta <file>');process.exitCode=1;}
}
