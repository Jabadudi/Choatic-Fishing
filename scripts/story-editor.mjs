// The story editor's bridge between the Reedwater Delta Atlas page and the game.
// Claude writes the chapters in code. The atlas (Edit world → Quests → Main story) lets their quest text and a few
// counts be changed on top: each chapter's title, recap, step names, objective lines and counts. It keeps one document
// per chapter in the collection `story` (id "ch6"; `story/_shared` holds lastEditAt/shippedAt).
//
//   node scripts/story-editor.mjs export <db-dir>   writes src/story-edits.js from <db-dir>/story/*.json
//   node scripts/story-editor.mjs meta <file>       writes the chapters as the code has them (world/story.json)
import {readdir,readFile,writeFile} from 'node:fs/promises';
import {join} from 'node:path';

const text=(v,max)=>typeof v==='string'?v.trim().replace(/\s+/g,' ').slice(0,max):'';
const PREFIX=/^Chapter \d+(?: complete)?\s*·\s*/;

// The chapters as written in code, in the shape the editor shows: steps with the objective line of each stage.
export async function baseStory(){
 const [{BASE_STORY_CHAPTERS},{STORY_OBJECTIVES},{STORY_COUNTS}]=await Promise.all([import('../src/story-quests.js'),import('../src/story.js'),import('../src/story-tuning.js')]);
 return {
  chapters:BASE_STORY_CHAPTERS.map(c=>({n:c.n,title:c.title,recap:c.recap,
   steps:c.steps.map(([stages,title])=>({id:stages[0],title,stages:stages.map(stage=>({stage,objective:(STORY_OBJECTIVES[stage]||'').replace(PREFIX,'')}))})),
   ...(c.end?{end:{stage:c.end,objective:(STORY_OBJECTIVES[c.end]||'').replace(PREFIX,'')}}:{}),
   counts:Object.entries(STORY_COUNTS).filter(([,k])=>k.chapter===c.n).map(([id,k])=>({id,...k}))}))
 };
}

// Editor documents to the edits the game applies: only what differs from the code, and only what the code has.
export function fromEditor(docs,base,notes=[]){
 const out={};
 for(const d of docs){
  if(d.id==='_shared')continue;
  const c=base.chapters.find(c=>`ch${c.n}`===d.id);if(!c){notes.push(`Skipped ${d.id}: no such chapter.`);continue;}
  const e={},stages=new Map([...c.steps.flatMap(s=>s.stages),...(c.end?[c.end]:[])].map(s=>[s.stage,s.objective]));
  const title=text(d.title,60);if(title&&title!==c.title)e.title=title;
  const recap=text(d.recap,600);if(recap&&recap!==c.recap)e.recap=recap;
  for(const [id,v] of Object.entries(d.steps||{})){const step=c.steps.find(s=>s.id===id),t=text(v,60);if(!step){notes.push(`Skipped a step name in ${d.id}: no step ${id}.`);continue;}if(t&&t!==step.title)(e.steps||={})[id]=t;}
  for(const [stage,v] of Object.entries(d.objectives||{})){
   if(!stages.has(stage)){notes.push(`Skipped an objective in ${d.id}: no stage ${stage}.`);continue;}
   if(!stages.get(stage)){notes.push(`Skipped the objective for ${stage}: the game writes that one itself.`);continue;}
   const t=text(v,300);if(t&&t!==stages.get(stage))(e.objectives||={})[stage]=t;
  }
  for(const [id,v] of Object.entries(d.counts||{})){
   const k=c.counts.find(k=>k.id===id);if(!k){notes.push(`Skipped count ${id} in ${d.id}.`);continue;}
   if(!Number.isFinite(v)){notes.push(`Skipped count ${id}: not a number.`);continue;}
   const n=Math.round(Math.min(k.max,Math.max(k.min,v)));if(n!==k.value)(e.counts||={})[id]=n;
  }
  if(Object.keys(e).length)out[c.n]=e;
 }
 return {chapters:out};
}

export function formatStoryEdits(edits){
 const j=v=>JSON.stringify(v).replace(/"([a-zA-Z_][a-zA-Z0-9_]*)":/g,'$1:');
 const field=(k,v)=>typeof v==='object'?`   ${k}:{\n${Object.entries(v).map(([a,b])=>`    ${JSON.stringify(a)}:${j(b)}`).join(',\n')}\n   }`:`   ${k}:${j(v)}`;
 const chapters=Object.entries(edits.chapters).sort(([a],[b])=>a-b).map(([n,e])=>`  ${n}:{\n${Object.entries(e).map(([k,v])=>field(k,v)).join(',\n')}\n  }`);
 return `// Edits to the main story's quest text and counts, made in the atlas (Edit world → Quests → Main story).
// Generated by scripts/story-editor.mjs from the atlas; only what differs from the story code is listed.
// Claude still writes the chapters in code; these edits sit on top. src/story-tuning.js applies them.
export const STORY_EDITS={
 chapters:{${chapters.length?`\n${chapters.join(',\n')}\n `:''}}
};
`;
}

async function readCollection(dir,name){
 const path=join(dir,name);let files=[];try{files=(await readdir(path)).filter(f=>f.endsWith('.json'));}catch{return [];}
 const docs=[];for(const f of files){const raw=JSON.parse(await readFile(join(path,f),'utf8'));const d=raw.data&&typeof raw.data==='object'?raw.data:raw;docs.push({...d,id:d.id||f.replace(/\.json$/,'')});}
 return docs;
}

if(import.meta.url===`file://${process.argv[1]}`){
 const [cmd,dir]=process.argv.slice(2);
 if(cmd==='export'&&dir){
  const notes=[],edits=fromEditor(await readCollection(dir,'story'),await baseStory(),notes);
  await writeFile('src/story-edits.js',formatStoryEdits(edits));
  console.log(`src/story-edits.js: edits in ${Object.keys(edits.chapters).length} chapters.`);
  for(const n of notes)console.log('  note:',n);
 }else if(cmd==='meta'&&dir){
  const base=await baseStory();await writeFile(dir,JSON.stringify(base));
  console.log(`${dir}: ${base.chapters.length} chapters.`);
 }else{console.log('Usage: node scripts/story-editor.mjs export <db-dir> | meta <file>');process.exitCode=1;}
}
